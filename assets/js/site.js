const translationAttributes = ['aria-label', 'alt', 'content', 'src', 'href'];
const translatedContent = Array.from(document.querySelectorAll('[data-i18n]'), (element) => ({
  element,
  key: element.dataset.i18n,
  english: element.innerHTML,
}));
const translatedAttributes = translationAttributes.flatMap((attribute) =>
  Array.from(document.querySelectorAll(`[data-i18n-${attribute}]`), (element) => ({
    element,
    attribute,
    key: element.getAttribute(`data-i18n-${attribute}`),
    english: element.getAttribute(attribute),
  }))
);
const languageSwitch = document.querySelector('.language-switch');
const languageButtons = Array.from(languageSwitch.querySelectorAll('[data-language]'));
const languageStorageKey = 'pintop-language';
let savedLanguage;

try {
  savedLanguage = localStorage.getItem(languageStorageKey);
} catch {
  // Language switching still works when browser storage is unavailable.
}

const browserLanguages = navigator.languages.length ? navigator.languages : [navigator.language];
const browserLanguage = browserLanguages
  .map((language) => language.toLowerCase().split('-')[0])
  .find((language) => language === 'en' || language === 'zh') || 'en';

function setLanguage(language) {
  document.documentElement.lang = language === 'zh' ? 'zh-Hans' : 'en';
  translatedContent.forEach(({ element, key, english }) => {
    element.innerHTML = language === 'zh' ? chineseTranslations[key] : english;
  });
  translatedAttributes.forEach(({ element, attribute, key, english }) => {
    element.setAttribute(attribute, language === 'zh' ? chineseTranslations[key] : english);
  });
  languageButtons.forEach((button) => {
    button.setAttribute('aria-pressed', String(button.dataset.language === language));
  });
}

setLanguage(savedLanguage === 'en' || savedLanguage === 'zh' ? savedLanguage : browserLanguage);
languageSwitch.hidden = false;

languageButtons.forEach((button) => {
  button.addEventListener('click', () => {
    const language = button.dataset.language;
    setLanguage(language);
    try {
      localStorage.setItem(languageStorageKey, language);
    } catch {
      // Keep the selected language for this visit even if it cannot be saved.
    }
  });
});


const menuToggle = document.querySelector('.menu-toggle');
const navigation = document.querySelector('#navigation');

document.documentElement.classList.add('js');
menuToggle.hidden = false;

function closeMenu() {
  menuToggle.setAttribute('aria-expanded', 'false');
  navigation.classList.remove('is-open');
}

menuToggle.addEventListener('click', () => {
  const isOpen = menuToggle.getAttribute('aria-expanded') === 'true';
  menuToggle.setAttribute('aria-expanded', String(!isOpen));
  navigation.classList.toggle('is-open', !isOpen);
});

navigation.addEventListener('click', (event) => {
  if (event.target.closest('a')) closeMenu();
});

document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape' && menuToggle.getAttribute('aria-expanded') === 'true') {
    closeMenu();
    menuToggle.focus();
  }
});

document.addEventListener('click', (event) => {
  if (!event.target.closest('.site-header')) closeMenu();
});

window.matchMedia('(max-width: 1100px)').addEventListener('change', closeMenu);
